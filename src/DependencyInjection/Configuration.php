<?php
declare(strict_types=1);

namespace Pringuin\OpenDxpHealthBundle\DependencyInjection;

use Pringuin\OpenDxpHealthBundle\Report\HealthStatus;
use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

final class Configuration implements ConfigurationInterface
{
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('pringuin_opendxp_health');
        $rootNode = $treeBuilder->getRootNode();

        $rootNode
            ->children()
                ->arrayNode('mail')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')
                            ->info('Send the health report via email when the command runs.')
                            ->defaultTrue()
                        ->end()
                        ->scalarNode('recipient')
                            ->info('Recipient address. Leave empty to use the main email address configured in OpenDXP (opendxp.email.sender.email).')
                            ->defaultNull()
                        ->end()
                        ->enumNode('min_status')
                            ->info('Lowest overall status that triggers a mail: "ok" sends every run, "warning" only when issues were found, "critical" only for critical findings and check execution errors, "error" only for checks that could not be executed.')
                            ->values(array_map(static fn (HealthStatus $status): string => $status->value, HealthStatus::cases()))
                            ->defaultValue(HealthStatus::WARNING->value)
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('checks')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('composer_audit')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->integerNode('process_timeout')
                                    ->info('Timeout in seconds for the composer audit process.')
                                    ->defaultValue(300)
                                    ->min(10)
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('message_queue')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->integerNode('max_age_hours')
                                    ->info('Messages older than this many hours that are still waiting in the queue are reported as stuck.')
                                    ->defaultValue(4)
                                    ->min(1)
                                ->end()
                                ->arrayNode('queue_names')
                                    ->info('Restrict the check to these queue names. Empty means all queues in the messenger table.')
                                    ->scalarPrototype()->end()
                                    ->defaultValue([])
                                ->end()
                                ->arrayNode('excluded_queue_names')
                                    ->info('Queues to ignore when queue_names is empty. The failure transport queue is covered by the failed_messages check.')
                                    ->scalarPrototype()->end()
                                    ->defaultValue(['failed'])
                                ->end()
                                ->scalarNode('table_name')
                                    ->info('Table used by the Doctrine messenger transport.')
                                    ->defaultValue('messenger_messages')
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('failed_messages')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->scalarNode('transport_name')
                                    ->info('Name of the messenger failure transport (framework.messenger.failure_transport).')
                                    ->defaultValue('failed')
                                ->end()
                                ->integerNode('list_limit')
                                    ->info('Maximum number of failed messages listed in the report details.')
                                    ->defaultValue(10)
                                    ->min(1)
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('maintenance')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->integerNode('max_age_minutes')
                                    ->info('Maximum accepted age of the last opendxp:maintenance run.')
                                    ->defaultValue(60)
                                    ->min(1)
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('application_log')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->integerNode('max_age_hours')
                                    ->info('Look for error entries within this time window.')
                                    ->defaultValue(24)
                                    ->min(1)
                                ->end()
                                ->arrayNode('priorities')
                                    ->info('Log priorities that are reported as issues.')
                                    ->scalarPrototype()->end()
                                    ->defaultValue(['emergency', 'alert', 'critical', 'error'])
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('email_log')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->integerNode('max_age_hours')
                                    ->info('Look for failed email deliveries and send volume peaks within this time window.')
                                    ->defaultValue(24)
                                    ->min(1)
                                ->end()
                                ->integerNode('max_emails_per_window')
                                    ->info('Warn when more emails than this were sent within any window_minutes long period. 0 disables the send volume check.')
                                    ->defaultValue(0)
                                    ->min(0)
                                ->end()
                                ->integerNode('window_minutes')
                                    ->info('Length of the sliding window used for max_emails_per_window.')
                                    ->defaultValue(60)
                                    ->min(1)
                                ->end()
                            ->end()
                            ->validate()
                                ->ifTrue(static fn (array $config): bool => $config['max_emails_per_window'] > 0
                                    && $config['window_minutes'] > $config['max_age_hours'] * 60)
                                ->thenInvalid('The email_log check cannot observe a send volume window longer than max_age_hours: %s')
                            ->end()
                        ->end()
                        ->arrayNode('doctrine_migrations')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                            ->end()
                        ->end()
                        ->arrayNode('environment')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->scalarNode('expected_environment')
                                    ->info('Expected Symfony kernel environment. Any other environment or enabled debug mode is reported as critical.')
                                    ->defaultValue('prod')
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('admin_two_factor')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                            ->end()
                        ->end()
                        ->arrayNode('table_growth')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->arrayNode('tables')
                                    ->info('Monitored tables with size thresholds in MB. Keys may contain SQL LIKE wildcards (%%); matching tables are aggregated per entry.')
                                    ->useAttributeAsKey('name')
                                    ->arrayPrototype()
                                        ->children()
                                            ->integerNode('warning_mb')->defaultValue(1024)->min(1)->end()
                                            ->integerNode('critical_mb')->defaultValue(4096)->min(1)->end()
                                        ->end()
                                    ->end()
                                    ->defaultValue([
                                        'versions' => ['warning_mb' => 2048, 'critical_mb' => 8192],
                                        'email_log' => ['warning_mb' => 512, 'critical_mb' => 2048],
                                        'messenger_messages' => ['warning_mb' => 512, 'critical_mb' => 2048],
                                        'application_logs%' => ['warning_mb' => 1024, 'critical_mb' => 4096],
                                        'tmp_store' => ['warning_mb' => 512, 'critical_mb' => 2048],
                                    ])
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('ssl_certificate')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->arrayNode('domains')
                                    ->info('Domains to check. Empty means auto-detect: main domain from the system settings plus all site domains.')
                                    ->scalarPrototype()->end()
                                    ->defaultValue([])
                                ->end()
                                ->integerNode('port')
                                    ->defaultValue(443)
                                    ->min(1)->max(65535)
                                ->end()
                                ->integerNode('connection_timeout')
                                    ->info('TLS connection timeout in seconds per domain.')
                                    ->defaultValue(10)
                                    ->min(1)
                                ->end()
                                ->integerNode('warning_days')
                                    ->info('Warn when a certificate expires within this many days.')
                                    ->defaultValue(21)
                                    ->min(1)
                                ->end()
                                ->integerNode('critical_days')
                                    ->info('Critical when a certificate expires within this many days.')
                                    ->defaultValue(7)
                                    ->min(1)
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('disk_space')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->arrayNode('paths')
                                    ->info('Directories whose filesystems are monitored. Relative paths are resolved against the project directory; paths on the same filesystem are measured once.')
                                    ->scalarPrototype()->end()
                                    ->defaultValue(['var', 'public/var'])
                                ->end()
                                ->integerNode('warning_percent')
                                    ->info('Warn when free disk space drops below this percentage.')
                                    ->defaultValue(15)
                                    ->min(1)->max(100)
                                ->end()
                                ->integerNode('critical_percent')
                                    ->info('Critical when free disk space drops below this percentage.')
                                    ->defaultValue(5)
                                    ->min(1)->max(100)
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('http_self_check')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->arrayNode('urls')
                                    ->info('URLs fetched from the server itself (e.g. homepage, login). Empty means nothing is checked.')
                                    ->scalarPrototype()->end()
                                    ->defaultValue([])
                                ->end()
                                ->arrayNode('expected_status_codes')
                                    ->info('HTTP status codes considered healthy.')
                                    ->integerPrototype()->end()
                                    ->defaultValue([200])
                                ->end()
                                ->integerNode('timeout')
                                    ->info('Request timeout in seconds per URL.')
                                    ->defaultValue(10)
                                    ->min(1)
                                ->end()
                                ->integerNode('warning_response_time_ms')
                                    ->info('Warn when a response takes at least this many milliseconds.')
                                    ->defaultValue(2000)
                                    ->min(1)
                                ->end()
                                ->integerNode('critical_response_time_ms')
                                    ->info('Critical when a response takes at least this many milliseconds.')
                                    ->defaultValue(5000)
                                    ->min(1)
                                ->end()
                                ->booleanNode('verify_tls')
                                    ->info('Verify the TLS certificate. Disable for internal self-calls with a hostname the certificate does not cover.')
                                    ->defaultTrue()
                                ->end()
                                ->integerNode('max_redirects')
                                    ->info('Redirects to follow; the report names the final URL. 0 checks the status code of the URL itself - add e.g. 301 to expected_status_codes where a redirect is intended.')
                                    ->defaultValue(20)
                                    ->min(0)
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('cache')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                            ->end()
                        ->end()
                        ->arrayNode('backup_age')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->scalarNode('directory')
                                    ->info('Directory holding the backup files. Empty means the check does nothing.')
                                    ->defaultNull()
                                ->end()
                                ->scalarNode('file_pattern')
                                    ->info('glob() pattern for backup files within the directory.')
                                    ->defaultValue('*')
                                ->end()
                                ->integerNode('warning_hours')
                                    ->info('Warn when the newest backup is at least this many hours old.')
                                    ->defaultValue(26)
                                    ->min(1)
                                ->end()
                                ->integerNode('critical_hours')
                                    ->info('Critical when the newest backup is at least this many hours old.')
                                    ->defaultValue(50)
                                    ->min(1)
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('composer_outdated')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->arrayNode('watch_packages')
                                    ->info('Packages highlighted separately and always reported as a warning when outdated.')
                                    ->scalarPrototype()->end()
                                    ->defaultValue(['open-dxp/opendxp'])
                                ->end()
                                ->integerNode('process_timeout')
                                    ->info('Timeout in seconds for the composer outdated process.')
                                    ->defaultValue(300)
                                    ->min(10)
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('php_version')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->integerNode('warning_days')
                                    ->info('Warn when the running PHP version reaches end of life within this many days.')
                                    ->defaultValue(90)
                                    ->min(1)
                                ->end()
                                ->arrayNode('eol_dates')
                                    ->info('Security-support end dates (Y-m-d) per minor version, e.g. "8.4": "2028-12-31". Merged over the built-in defaults.')
                                    ->useAttributeAsKey('version')
                                    ->scalarPrototype()->end()
                                    ->defaultValue([])
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('writable_paths')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->arrayNode('paths')
                                    ->info('Directories checked for writability. Relative paths are resolved against the project directory.')
                                    ->scalarPrototype()->end()
                                    ->defaultValue(['var/cache', 'var/log', 'var/tmp', 'public/var'])
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('status_endpoint')
                    ->addDefaultsIfNotSet()
                    ->info('Public, token-protected endpoint (/pringuin/health/status) exposing the last report for external uptime monitoring.')
                    ->children()
                        ->booleanNode('enabled')
                            ->info('Disabled by default. Without a configured token of at least 32 characters the endpoint stays hidden (404).')
                            ->defaultFalse()
                        ->end()
                        ->scalarNode('token')
                            ->info('Shared secret of at least 32 characters, sent as "Authorization: Bearer <token>", as X-Health-Token header or as "token" query parameter.')
                            ->defaultNull()
                        ->end()
                        ->booleanNode('expose_details')
                            ->info('Include the full report (check summaries and details, domain, host name) in the response. The details can contain user names, email addresses, log excerpts and vulnerable package versions.')
                            ->defaultFalse()
                        ->end()
                    ->end()
                ->end()
            ->end();

        return $treeBuilder;
    }
}
